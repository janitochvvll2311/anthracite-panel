import { execFileSync } from "node:child_process";
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";

export const wasmTools =
  process.env.WASM_TOOLS ?? Bun.which("wasm-tools") ?? "/tools/cargo/bin/wasm-tools";
const rustfmt = process.env.RUSTFMT ?? Bun.which("rustfmt") ?? "/tools/cargo/bin/rustfmt";
export const scratch = process.env.ANTH_SCRATCH ?? "/tmp/anthracite-panel";

export const header = "// Generated by scripts/codegen.ts; do not edit.\n";

export function fail(message: string): never {
  console.error(message);
  process.exit(1);
}

/// The generated Rust is checked by the workspace's `cargo fmt --check`; format
/// it here so the checked-in bytes and the codegen output agree.
export function formatRust(source: string): string {
  mkdirSync(scratch, { recursive: true });
  const dir = mkdtempSync(join(scratch, "rustfmt-"));
  try {
    const path = join(dir, "generated.rs");
    writeFileSync(path, source);
    execFileSync(
      rustfmt,
      ["--edition", "2021", "--config", "skip_children=true", path],
      { encoding: "utf8", maxBuffer: 8 * 1024 * 1024 },
    );
    return readFileSync(path, "utf8");
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

export function pascal(name: string): string {
  return name
    .split(/[-_]/)
    .filter(Boolean)
    .map((part) => part[0]?.toUpperCase() + part.slice(1))
    .join("");
}

export function snake(name: string): string {
  return name.replace(/-/g, "_");
}

/// A package name contains `:` and `@`; generated modules and type keys must be
/// valid identifiers and unique across packages.
export function token(name: string): string {
  return name
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "_")
    .replace(/^_+|_+$/g, "");
}

export function camel(name: string): string {
  const value = pascal(name);
  return value[0]?.toLowerCase() + value.slice(1);
}

const RUST_KEYWORDS = new Set([
  "as", "break", "const", "continue", "crate", "else", "enum", "extern",
  "false", "fn", "for", "if", "impl", "in", "let", "loop", "match", "mod",
  "move", "mut", "pub", "ref", "return", "self", "Self", "static", "struct",
  "super", "trait", "true", "type", "unsafe", "use", "where", "while", "async",
  "await", "dyn", "abstract", "become", "box", "do", "final", "macro",
  "override", "priv", "typeof", "unsized", "virtual", "yield", "try",
]);

const RUST_RAW_FORBIDDEN = new Set(["self", "Self", "crate", "super"]);

export function rustField(name: string): string {
  const value = snake(name);
  if (RUST_RAW_FORBIDDEN.has(value)) return `${value}_`;
  return RUST_KEYWORDS.has(value) ? `r#${value}` : value;
}

/// Enum variants are type-level names, so `Self` is reserved. The `serde`
/// attribute carries the wire name, so the variant itself can be renamed.
export function rustVariant(name: string): string {
  const value = pascal(name);
  return value === "Self" ? "SelfValue" : value;
}

