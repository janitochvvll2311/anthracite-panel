#!/usr/bin/env bun
// WIT -> typed clients and the app's command table.
//
// The engine reads the route signature at runtime; this generator keeps the
// Rust and TypeScript clients from inventing a second mapping. It is deliberately
// small and deterministic: the output is checked in and CI runs `--check`.

import { execFileSync } from "node:child_process";
import {
  cpSync,
  existsSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  readdirSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { dirname, join, resolve } from "node:path";

type TypeRef = string | number;
type WitType = { name: string | null; kind: any; owner: any };
type WitFunction = {
  name: string;
  kind: string;
  params: { name: string; type: TypeRef }[];
  result?: TypeRef;
};
type WitInterface = {
  name: string | null;
  types: Record<string, TypeRef>;
  functions: Record<string, WitFunction>;
  package: number;
};
type WitDoc = {
  packages: { name: string; interfaces: Record<string, number> }[];
  interfaces: WitInterface[];
  types: WitType[];
};

const root = resolve(import.meta.dir, "..");
const args = process.argv.slice(2);
const check = args.includes("--check");
const appArg = args.find((arg) => !arg.startsWith("--")) ?? "apps/hello";
const appDir = resolve(root, appArg);
const catalog = process.env.ANTH_GUEST_WIT ?? join(root, "sdk/rust/guest/wit/deps");
const wasmTools =
  process.env.WASM_TOOLS ?? Bun.which("wasm-tools") ?? "/tools/cargo/bin/wasm-tools";
const rustfmt = process.env.RUSTFMT ?? Bun.which("rustfmt") ?? "/tools/cargo/bin/rustfmt";
const scratch = process.env.ANTH_SCRATCH ?? "/tmp/anthracite-panel";

const header = "// Generated by scripts/codegen.ts; do not edit.\n";

function fail(message: string): never {
  console.error(message);
  process.exit(1);
}

/// The generated Rust is checked by the workspace's `cargo fmt --check`; format
/// it here so the checked-in bytes and the codegen output agree.
function formatRust(source: string): string {
  mkdirSync(scratch, { recursive: true });
  const dir = mkdtempSync(join(scratch, "rustfmt-"));
  try {
    const path = join(dir, "generated.rs");
    writeFileSync(path, source);
    execFileSync(
      rustfmt,
      ["--edition", "2021", "--config", "skip_children=true", path],
      { encoding: "utf8", maxBuffer: 8 * 1024 * 1024 },
    );
    return readFileSync(path, "utf8");
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

function pascal(name: string): string {
  return name
    .split(/[-_]/)
    .filter(Boolean)
    .map((part) => part[0]?.toUpperCase() + part.slice(1))
    .join("");
}

function snake(name: string): string {
  return name.replace(/-/g, "_");
}

function camel(name: string): string {
  const value = pascal(name);
  return value[0]?.toLowerCase() + value.slice(1);
}

const RUST_KEYWORDS = new Set([
  "as", "break", "const", "continue", "crate", "else", "enum", "extern",
  "false", "fn", "for", "if", "impl", "in", "let", "loop", "match", "mod",
  "move", "mut", "pub", "ref", "return", "self", "Self", "static", "struct",
  "super", "trait", "true", "type", "unsafe", "use", "where", "while", "async",
  "await", "dyn", "abstract", "become", "box", "do", "final", "macro",
  "override", "priv", "typeof", "unsized", "virtual", "yield", "try",
]);

const RUST_RAW_FORBIDDEN = new Set(["self", "Self", "crate", "super"]);

function rustField(name: string): string {
  const value = snake(name);
  if (RUST_RAW_FORBIDDEN.has(value)) return `${value}_`;
  return RUST_KEYWORDS.has(value) ? `r#${value}` : value;
}

function witType(doc: WitDoc, ref: TypeRef): WitType {
  if (typeof ref !== "number") fail(`expected a type id, got \`${ref}\``);
  const type = doc.types[ref];
  if (!type) fail(`type id ${ref} is missing`);
  return type;
}

function packageName(doc: WitDoc, index: number): string {
  return doc.packages[index]?.name ?? fail(`package ${index} is missing`);
}

function splitPackage(name: string): { base: string; version: string } {
  const at = name.lastIndexOf("@");
  if (at < 0) return { base: name, version: "0.0.0" };
  return { base: name.slice(0, at), version: name.slice(at + 1) };
}

function interfaceId(doc: WitDoc, iface: WitInterface): string {
  const pkg = splitPackage(packageName(doc, iface.package));
  return `${pkg.base}/${iface.name}@${pkg.version}`;
}

function parseWit(app: string, deps: string): WitDoc {
  if (!existsSync(deps)) fail(`the guest WIT catalog is missing at ${deps}`);
  mkdirSync(scratch, { recursive: true });
  const tmp = mkdtempSync(join(scratch, "codegen-"));
  try {
    mkdirSync(join(tmp, "deps"), { recursive: true });
    for (const file of readdirSync(join(app, "wit"))) {
      if (file.endsWith(".wit")) {
        cpSync(join(app, "wit", file), join(tmp, file));
      }
    }
    cpSync(deps, join(tmp, "deps"), { recursive: true });
    const json = execFileSync(
      wasmTools,
      ["component", "wit", tmp, "--json"],
      { encoding: "utf8", maxBuffer: 64 * 1024 * 1024 },
    );
    return JSON.parse(json) as WitDoc;
  } finally {
    rmSync(tmp, { recursive: true, force: true });
  }
}

function primitive(ref: string): boolean {
  return new Set([
    "string", "bool", "u8", "u16", "u32", "u64", "s8", "s16", "s32", "s64",
    "f32", "f64", "bytes",
  ]).has(ref);
}

function tsPrimitive(ref: string): string {
  switch (ref) {
    case "string":
      return "string";
    case "bool":
      return "boolean";
    case "u8":
    case "u16":
    case "u32":
    case "u64":
    case "s8":
    case "s16":
    case "s32":
    case "s64":
    case "f32":
    case "f64":
      return "number";
    case "bytes":
      return "Uint8Array";
    default:
      return fail(`unsupported WIT type \`${ref}\``);
  }
}

function rustPrimitive(ref: string): string {
  if (primitive(ref)) {
    return ref === "string" ? "String" : ref === "bytes" ? "Vec<u8>" : ref;
  }
  return fail(`unsupported WIT type \`${ref}\``);
}

type Generation = {
  files: Record<string, string>;
};

function generate(): Generation {
  const manifest = Bun.TOML.parse(
    readFileSync(join(appDir, "manifest.toml"), "utf8"),
  ) as any;
  const doc = parseWit(appDir, catalog);
  const routes = new Map<string, any>();
  for (const route of manifest.route ?? []) {
    routes.set(route.call, route);
  }
  const verbs = new Map<string, string>();
  for (const entry of manifest.cli ?? []) {
    verbs.set(entry.call, entry.verb);
  }

  const exported: { id: string; iface: WitInterface }[] = [];
  for (const entry of manifest.export ?? []) {
    const iface = doc.interfaces.find((candidate) =>
      interfaceId(doc, candidate) === entry.interface,
    );
    if (!iface) fail(`exported interface \`${entry.interface}\` is missing from WIT`);
    exported.push({ id: entry.interface, iface });
  }

  const named = new Map<string, WitType>();
  const tsTypeCache = new Map<number, string>();
  const rustTypeCache = new Map<number, string>();

  function typeKey(type: WitType): string {
    if (!type.name) fail("an anonymous type cannot be named");
    const owner = type.owner?.interface;
    const iface =
      typeof owner === "number" ? doc.interfaces[owner] : undefined;
    return `${iface?.name ? pascal(iface.name) : ""}${pascal(type.name)}`;
  }

  function ensureNamed(type: WitType): void {
    if (!type.name) return;
    const key = typeKey(type);
    if (named.has(key)) return;
    named.set(key, type);
    if (type.kind.record) {
      for (const field of type.kind.record.fields) collect(field.type);
    }
    // Enums have no payloads. Variants are not accepted in route signatures.
  }

  function collect(ref: TypeRef): void {
    if (typeof ref === "string") {
      if (!primitive(ref)) fail(`unsupported WIT type \`${ref}\``);
      return;
    }
    const type = witType(doc, ref);
    if (type.name) {
      ensureNamed(type);
      return;
    }
    const kind = type.kind;
    if (kind.list) collect(kind.list);
    else if (kind.option) collect(kind.option);
    else if (kind.type) collect(kind.type);
    else if (kind.result) {
      if (kind.result.ok !== null && kind.result.ok !== undefined) {
        collect(kind.result.ok);
      }
    } else {
      fail(`unsupported anonymous WIT type ${JSON.stringify(kind)}`);
    }
  }

  function returnRef(fn: WitFunction): TypeRef | null {
    if (fn.result === undefined || fn.result === null) return null;
    if (typeof fn.result === "number") {
      const type = witType(doc, fn.result);
      if (!type.name && type.kind.result) return type.kind.result.ok ?? null;
    }
    return fn.result;
  }

  function tsType(ref: TypeRef): string {
    if (typeof ref === "string") return tsPrimitive(ref);
    const type = witType(doc, ref);
    if (type.name) return `types.${typeKey(type)}`;
    if (tsTypeCache.has(ref)) return tsTypeCache.get(ref)!;
    const kind = type.kind;
    let value: string;
    if (kind.list) value = `${tsType(kind.list)}[]`;
    else if (kind.option) value = `${tsType(kind.option)} | null`;
    else if (kind.type) value = tsType(kind.type);
    else if (kind.result) {
      value = kind.result.ok === null || kind.result.ok === undefined
        ? "void"
        : tsType(kind.result.ok);
    } else {
      fail(`unsupported WIT type in a route signature: ${JSON.stringify(kind)}`);
    }
    tsTypeCache.set(ref, value);
    return value;
  }

  function rustType(ref: TypeRef): string {
    if (typeof ref === "string") return rustPrimitive(ref);
    const type = witType(doc, ref);
    if (type.name) return `crate::types::${typeKey(type)}`;
    if (rustTypeCache.has(ref)) return rustTypeCache.get(ref)!;
    const kind = type.kind;
    let value: string;
    if (kind.list) value = `Vec<${rustType(kind.list)}>`;
    else if (kind.option) value = `Option<${rustType(kind.option)}>`;
    else if (kind.type) value = rustType(kind.type);
    else if (kind.result) {
      value = kind.result.ok === null || kind.result.ok === undefined
        ? "()"
        : rustType(kind.result.ok);
    } else {
      fail(`unsupported WIT type in a route signature: ${JSON.stringify(kind)}`);
    }
    rustTypeCache.set(ref, value);
    return value;
  }

  function typeLabel(ref: TypeRef | null): string {
    if (ref === null) return "unit";
    if (typeof ref === "string") return ref;
    const type = witType(doc, ref);
    if (type.name) return type.name;
    const kind = type.kind;
    if (kind.list) return `list<${typeLabel(kind.list)}>`;
    if (kind.option) return `option<${typeLabel(kind.option)}>`;
    if (kind.type) return typeLabel(kind.type);
    if (kind.result) return typeLabel(kind.result.ok ?? null);
    return "unknown";
  }

  function isOption(ref: TypeRef): boolean {
    if (typeof ref !== "number") return false;
    const type = witType(doc, ref);
    return !type.name && Boolean(type.kind.option);
  }

  function inner(ref: TypeRef): TypeRef {
    if (typeof ref !== "number") return ref;
    const type = witType(doc, ref);
    return type.kind.option ?? ref;
  }

  function isRecord(ref: TypeRef): boolean {
    if (typeof ref !== "number") return false;
    const type = witType(doc, ref);
    if (type.name) return Boolean(type.kind.record);
    return false;
  }

  function tsParamType(ref: TypeRef): string {
    const value = isOption(ref) ? inner(ref) : ref;
    return tsType(value);
  }

  function rustParamType(ref: TypeRef): string {
    const value = isOption(ref) ? inner(ref) : ref;
    return isOption(ref) ? `Option<${rustType(value)}>` : rustType(value);
  }

  function tsParams(fn: WitFunction): string {
    return fn.params
      .map((param) => {
        for (const ref of [param.type]) collect(ref);
        const optional = isOption(param.type);
        return `${camel(param.name)}: ${tsParamType(param.type)}${optional ? " | null" : ""}`;
      })
      .join(", ");
  }

  function rustParams(fn: WitFunction): string {
    return fn.params
      .map((param) => {
        for (const ref of [param.type]) collect(ref);
        return `${rustField(param.name)}: ${rustParamType(param.type)}`;
      })
      .join(", ");
  }

  function tsQuery(fn: WitFunction): { declarations: string[]; appends: string[] } {
    const declarations = ["    const __gen_query = new URLSearchParams();"];
    const appends: string[] = [];
    for (const param of fn.params) {
      const ref = isOption(param.type) ? inner(param.type) : param.type;
      const name = camel(param.name);
      const list = typeof ref === "number" && Boolean(witType(doc, ref).kind?.list);
      const key = list ? `${param.name}[]` : param.name;
      const append = (value: string) =>
        `      __gen_query.append(${JSON.stringify(key)}, ${value});`;
      if (isOption(param.type)) {
        appends.push(
          `    if (${name} !== undefined && ${name} !== null) {`,
        );
      }
      if (list) {
        appends.push(`    for (const __gen_value of ${name}) {`);
        appends.push(append("String(__gen_value)"));
        appends.push("    }");
      } else {
        if (typeof ref === "number" && witType(doc, ref).kind?.record) {
          fail("a record cannot be used in a query; use POST/PUT/PATCH");
        }
        appends.push(append(`String(${name})`));
      }
      if (isOption(param.type)) appends.push("    }");
    }
    return { declarations, appends };
  }

  function rustQuery(fn: WitFunction): { declarations: string[]; appends: string[] } {
    const declarations = ["        let mut __gen_query = Vec::new();"];
    const appends: string[] = [];
    for (const param of fn.params) {
      const ref = isOption(param.type) ? inner(param.type) : param.type;
      const name = rustField(param.name);
      const list = typeof ref === "number" && Boolean(witType(doc, ref).kind?.list);
      const key = list ? `${param.name}[]` : param.name;
      const append = (value: string) =>
        `            __gen_query.push(format!("{}={}", ${JSON.stringify(key)}, crate::query_value(&${value})?));`;
      if (isOption(param.type)) {
        appends.push(`        if let Some(__gen_value) = &${name} {`);
        if (list) {
          appends.push("            for __gen_value in __gen_value {");
          appends.push(append("__gen_value"));
          appends.push("            }");
        } else {
          appends.push(append("__gen_value"));
        }
        appends.push("        }");
      } else if (list) {
        appends.push(`        for __gen_value in &${name} {`);
        appends.push(append("__gen_value"));
        appends.push("        }");
      } else {
        if (typeof ref === "number" && witType(doc, ref).kind?.record) {
          fail("a record cannot be used in a query; use POST/PUT/PATCH");
        }
        appends.push(append(name));
      }
    }
    return { declarations, appends };
  }

  function tsBody(fn: WitFunction, method: string): string | null {
    if (["GET", "HEAD", "DELETE"].includes(method)) return null;
    if (fn.params.length === 1 && isRecord(fn.params[0].type)) {
      return `    const __gen_body = JSON.stringify(${camel(fn.params[0].name)});`;
    }
    if (fn.params.length === 0) return null;
    const fields = fn.params
      .map((param) => `${JSON.stringify(param.name)}: ${camel(param.name)}`)
      .join(", ");
    return `    const __gen_body = JSON.stringify({ ${fields} });`;
  }

  function rustBody(fn: WitFunction, method: string): string | null {
    if (["GET", "HEAD", "DELETE"].includes(method)) return null;
    if (fn.params.length === 1 && isRecord(fn.params[0].type)) {
      return `        let __gen_body = serde_json::to_string(&${rustField(fn.params[0].name)})
            .map_err(|error| crate::ClientError::new(format!("cannot encode the body: {error}")))?;`;
    }
    if (fn.params.length === 0) return null;
    const fields = fn.params
      .map((param) => `${JSON.stringify(param.name)}: ${rustField(param.name)}`)
      .join(", ");
    return `        let __gen_body = serde_json::to_string(&serde_json::json!({ ${fields} }))
            .map_err(|error| crate::ClientError::new(format!("cannot encode the body: {error}")))?;`;
  }

  function tsMethod(fn: WitFunction, route: any): string {
    const method = String(route.method).toUpperCase();
    const params = tsParams(fn);
    const returnType = returnRef(fn);
    for (const ref of returnType === null ? [] : [returnType]) collect(ref);
    const usesQuery = ["GET", "HEAD", "DELETE"].includes(method);
    const query = usesQuery ? tsQuery(fn) : { declarations: [], appends: [] };
    const body = tsBody(fn, method);
    const lines: string[] = [];
    lines.push(
      `  async ${camel(fn.name)}(${params}): Promise<${returnType === null ? "void" : tsType(returnType)}> {`,
    );
    if (query.appends.length > 0) {
      lines.push(...query.declarations, ...query.appends);
      lines.push(`    const __gen_qs = __gen_query.toString();`);
      lines.push(
        `    const __gen_path = \`\${this.base}${route.path}\${__gen_qs ? \`?\${__gen_qs}\` : ""}\`;`,
      );
    } else {
      lines.push(`    const __gen_path = \`\${this.base}${route.path}\`;`);
    }
    if (body) lines.push(body);
    if (returnType === null) {
      lines.push(
        `    await this.request("${method}", __gen_path${body ? ", __gen_body" : ""});`,
      );
    } else {
      lines.push(
        `    const __gen_text = await this.request("${method}", __gen_path${body ? ", __gen_body" : ""});`,
      );
      lines.push(`    return JSON.parse(__gen_text) as ${tsType(returnType)};`);
    }
    lines.push("  }");
    return lines.join("\n");
  }

  function rustMethod(fn: WitFunction, route: any): string {
    const method = String(route.method).toUpperCase();
    const params = rustParams(fn);
    const returnType = returnRef(fn);
    for (const ref of returnType === null ? [] : [returnType]) collect(ref);
    const usesQuery = ["GET", "HEAD", "DELETE"].includes(method);
    const query = usesQuery ? rustQuery(fn) : { declarations: [], appends: [] };
    const body = rustBody(fn, method);
    const lines: string[] = [];
    const result = returnType === null ? "()" : rustType(returnType);
    lines.push(
      `    pub fn ${snake(fn.name)}(&self${params ? `, ${params}` : ""}) -> Result<${result}, crate::ClientError> {`,
    );
    if (query.appends.length > 0) lines.push(...query.declarations, ...query.appends);
    if (query.appends.length > 0) {
      lines.push(`        let mut __gen_path = format!("{}{}", self.base, ${JSON.stringify(route.path)});`);
      lines.push("        if !__gen_query.is_empty() {");
      lines.push("            __gen_path.push('?');");
      lines.push("            __gen_path.push_str(&__gen_query.join(\"&\"));");
      lines.push("        }");
    } else {
      lines.push(`        let __gen_path = format!("{}{}", self.base, ${JSON.stringify(route.path)});`);
    }
    if (body) lines.push(body);
    lines.push(
      `        let __gen_text = self.transport.request("${method}", &__gen_path, ${body ? "Some(&__gen_body)" : "None"})?;`,
    );
    if (returnType === null) {
      lines.push("        Ok(())");
    } else {
      lines.push(
        `        serde_json::from_str::<${rustType(returnType)}>(&__gen_text)
            .map_err(|error| crate::ClientError::new(format!("invalid JSON: {error}")))`,
      );
    }
    lines.push("    }");
    return lines.join("\n");
  }

  const tsTypes: string[] = [];
  const rustTypes: string[] = [];
  const tsInterfaces: string[] = [];
  const rustInterfaces: string[] = [];
  const httpExportsTs: string[] = [];
  const httpExportsRust: string[] = [];
  const classByInterface = new Map<string, { className: string; module: string }>();

  const generatedInterfaces: string[] = [];
  for (const { iface } of exported) {
    const methods: { fn: WitFunction; route: any }[] = [];
    for (const fn of Object.values(iface.functions)) {
      const call = `${interfaceId(doc, iface)}#${fn.name}`;
      const route = routes.get(call);
      if (route) methods.push({ fn, route });
    }
    if (methods.length === 0) continue;
    const module = snake(iface.name ?? "client");
    const classname = `${pascal(iface.name ?? "client")}HttpClient`;
    const tsLines = [
      header,
      `import type { Transport } from "./transport";`,
      `import type * as types from "./types";`,
      "",
      `// HTTP/route client. The transport is an HTTP adapter (UDS, TCP, fetch).`,
      `export class ${classname} {`,
      `  constructor(private readonly request: Transport, private readonly base = "/api/apps/${manifest.app.id}") {}`,
      ...methods.map(({ fn, route }) => tsMethod(fn, route)),
      "}",
      "",
    ];
    tsInterfaces.push(tsLines.join("\n"));
    const rustLines = [
      header,
      `/// HTTP/route client. The transport is an HTTP adapter (UDS, TCP, fetch).`,
      `pub struct ${classname}<T: crate::Transport> {`,
      "    transport: T,",
      "    base: String,",
      "}",
      "",
      `impl<T: crate::Transport> ${classname}<T> {`,
      "    pub fn new(transport: T) -> Self {",
      `        Self { transport, base: "/api/apps/${manifest.app.id}".to_string() }`,
      "    }",
      "",
      "    pub fn with_base(transport: T, base: impl Into<String>) -> Self {",
      "        Self { transport, base: base.into() }",
      "    }",
      ...methods.map(({ fn, route }) => rustMethod(fn, route)),
      "}",
      "",
    ];
    rustInterfaces.push(rustLines.join("\n"));
    generatedInterfaces.push(module);
    httpExportsTs.push(`export * from "./${module}";`);
    httpExportsRust.push(`pub use crate::${module}::*;`);
    classByInterface.set(interfaceId(doc, iface), { className: classname, module });
  }

  // Named records and enums referenced by route signatures.
  for (const type of [...named.values()].sort((a, b) =>
    typeKey(a) < typeKey(b) ? -1 : 1,
  )) {
    const name = typeKey(type);
    if (type.kind.record) {
      const fields = type.kind.record.fields as { name: string; type: TypeRef }[];
      const tsFields = fields
        .map((field) => {
          collect(field.type);
          const key = /^[A-Za-z_$][\w$]*$/.test(field.name)
            ? field.name
            : JSON.stringify(field.name);
          return `  ${key}: ${tsType(field.type)};`;
        })
        .join("\n");
      tsTypes.push(`export interface ${name} {\n${tsFields}\n}\n`);
      const rustFields = fields
        .map((field) => {
          collect(field.type);
          return `    #[serde(rename = ${JSON.stringify(field.name)})]\n    pub ${rustField(field.name)}: ${rustType(field.type)},`;
        })
        .join("\n");
      rustTypes.push(
        `#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]\n#[serde(deny_unknown_fields)]\npub struct ${name} {\n${rustFields}\n}\n`,
      );
    } else if (type.kind.enum) {
      const cases = type.kind.enum.cases as { name: string }[];
      tsTypes.push(
        `export type ${name} = ${cases.map((c) => JSON.stringify(c.name)).join(" | ")};\n`,
      );
      rustTypes.push(
        `#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]\n#[serde(rename_all = "kebab-case")]\npub enum ${name} {\n${cases
          .map((c) => `    ${pascal(c.name)},`)
          .join("\n")}\n}\n`,
      );
      rustTypes.push(
        `impl ${name} {\n    pub fn parse(value: &str) -> Option<Self> {\n        match value {\n${cases
          .map(
            (c) =>
              `            ${JSON.stringify(c.name)} => Some(Self::${pascal(c.name)}),`,
          )
          .join("\n")}\n            _ => None,\n        }\n    }\n}\n`,
      );
    } else {
      fail(`named type \`${type.name}\` is not a record or enum`);
    }
  }

  const commands: any[] = [];
  const cliEntries: {
    verb: string;
    fn: WitFunction;
    route: any | undefined;
    client: { className: string; module: string } | undefined;
  }[] = [];
  for (const entry of manifest.cli ?? []) {
    const [ifaceId, functionName] = String(entry.call).split("#");
    const iface = doc.interfaces.find(
      (candidate) => interfaceId(doc, candidate) === ifaceId,
    );
    if (!iface) fail(`CLI call \`${entry.call}\` names an unknown interface`);
    const fn = iface.functions[functionName];
    if (!fn) fail(`CLI call \`${entry.call}\` names an unknown function`);
    for (const param of fn.params) collect(param.type);
    const route = routes.get(entry.call);
    commands.push({
      verb: entry.verb,
      method: route ? String(route.method).toUpperCase() : null,
      path: route ? route.path : null,
      interface: ifaceId,
      function: functionName,
      params: fn.params.map((param) => ({
        name: param.name,
        type: typeLabel(param.type),
        optional: isOption(param.type),
      })),
      returns: typeLabel(returnRef(fn)),
    });
    cliEntries.push({
      verb: entry.verb,
      fn,
      route,
      client: classByInterface.get(ifaceId),
    });
  }

  // -------------------------------------------------------------------------
  // CLI clients. They receive the same Transport as the HTTP clients; the
  // transport is the adapter (UDS, TCP, fetch, ...) and this module only parses
  // flags and calls the typed route methods.

  function cliBase(ref: TypeRef): TypeRef {
    return isOption(ref) ? inner(ref) : ref;
  }

  function cliList(ref: TypeRef): boolean {
    return typeof ref === "number" && Boolean(witType(doc, ref).kind?.list);
  }

  function cliBool(ref: TypeRef): boolean {
    return typeof ref === "string" && ref === "bool";
  }

  function tsParseValue(ref: TypeRef, expression: string): string {
    if (typeof ref === "string") {
      if (ref === "string") return expression;
      if (ref === "bool") return `(${expression} === "true" || ${expression} === "1")`;
      if (ref === "bytes") return `new TextEncoder().encode(${expression})`;
      if (["u8", "u16", "u32", "u64", "s8", "s16", "s32", "s64", "f32", "f64"].includes(ref)) {
        return `Number(${expression})`;
      }
      fail(`unsupported CLI parameter type \`${ref}\``);
    }
    const type = witType(doc, ref);
    if (type.name) {
      if (type.kind.enum) return `(${expression} as types.${typeKey(type)})`;
      if (type.kind.record) {
        return `(JSON.parse(${expression}) as types.${typeKey(type)})`;
      }
      fail(`named type \`${type.name}\` cannot be parsed by the CLI`);
    }
    const kind = type.kind;
    if (kind.list) return `(JSON.parse(${expression}) as ${tsType(ref)})`;
    if (kind.option) return tsParseValue(kind.option, expression);
    if (kind.type) return tsParseValue(kind.type, expression);
    fail(`unsupported CLI parameter type: ${JSON.stringify(kind)}`);
  }

  function rustParseValue(ref: TypeRef, expression: string): string {
    if (typeof ref === "string") {
      if (ref === "string") return expression;
      if (ref === "bool") {
        return `${expression}.parse::<bool>().map_err(|_| crate::ClientError::new("expected a boolean"))?`;
      }
      if (ref === "bytes") return `${expression}.into_bytes()`;
      if (["u8", "u16", "u32", "u64", "s8", "s16", "s32", "s64", "f32", "f64"].includes(ref)) {
        return `${expression}.parse::<${rustPrimitive(ref)}>().map_err(|_| crate::ClientError::new("expected a number"))?`;
      }
      fail(`unsupported CLI parameter type \`${ref}\``);
    }
    const type = witType(doc, ref);
    if (type.name) {
      if (type.kind.enum) {
        return `crate::types::${typeKey(type)}::parse(&${expression}).ok_or_else(|| crate::ClientError::new("invalid enum value"))?`;
      }
      if (type.kind.record) {
        return `serde_json::from_str::<crate::types::${typeKey(type)}>(&${expression}).map_err(|error| crate::ClientError::new(format!("invalid JSON: {error}")))?`;
      }
      fail(`named type \`${type.name}\` cannot be parsed by the CLI`);
    }
    const kind = type.kind;
    if (kind.list) {
      return `serde_json::from_str::<${rustType(ref)}>(&${expression}).map_err(|error| crate::ClientError::new(format!("invalid JSON: {error}")))?`;
    }
    if (kind.option) return rustParseValue(kind.option, expression);
    if (kind.type) return rustParseValue(kind.type, expression);
    fail(`unsupported CLI parameter type: ${JSON.stringify(kind)}`);
  }

  const cliClients = [
    ...new Map(
      cliEntries
        .filter((entry) => entry.client)
        .map((entry) => [entry.client!.className, entry.client!] as const),
    ).values(),
  ];
  const cliTs: string[] = [
    header,
    `import type { Transport } from "./transport";`,
    `import * as types from "./types";`,
    "",
    `// CLI client. Parses flags and delegates to the HTTP client over the same transport.`,
  ];
  if (cliClients.length > 0) {
    cliTs.push(
      `import { ${cliClients.map((client) => client.className).join(", ")} } from "./http";`,
    );
  }
  cliTs.push(
    "",
    "export async function run(transport: Transport, verb: string, args: string[]): Promise<string> {",
    "  switch (verb) {",
  );

  const cliRust: string[] = [
    header,
    "use crate::{ClientError, Transport};",
    "",
    "/// CLI client. Parses flags and delegates to the HTTP client over the same transport.",
  ];
  if (cliClients.length === 1) {
    cliRust.push(`use crate::http::${cliClients[0].className};`);
  } else if (cliClients.length > 1) {
    cliRust.push(
      `use crate::http::{${cliClients.map((client) => client.className).join(", ")}};`,
    );
  }
  cliRust.push(
    "",
    "pub fn run<T: Transport>(transport: T, verb: &str, args: &[String]) -> Result<String, ClientError> {",
    "    let _ = &transport;",
    "    match verb {",
  );

  for (const entry of cliEntries) {
    if (!entry.route || !entry.client) {
      cliTs.push(
        `    case ${JSON.stringify(entry.verb)}:`,
        `      throw new Error(${JSON.stringify(`verb \`${entry.verb}\` is unavailable: no route`)});`,
      );
      cliRust.push(
        `        ${JSON.stringify(entry.verb)} => Err(ClientError::new(${JSON.stringify(
          `verb \`${entry.verb}\` is unavailable: no route`,
        )})),`,
      );
      continue;
    }

    const declarations: string[] = [];
    const cases: string[] = [];
    const finals: string[] = [];
    const argsUsed: string[] = [];

    for (const param of entry.fn.params) {
      const base = cliBase(param.type);
      const optional = isOption(param.type);
      const name = `__arg_${camel(param.name)}`;
      const flag = `--${param.name}`;
      argsUsed.push(isOption(param.type) ? `(${name} ?? null)` : name);
      if (cliList(base)) {
        const listRef = witType(doc, base as number).kind.list;
        if (optional) {
          declarations.push(`      let ${name}: ${tsType(base)} | undefined;`);
          cases.push(
            `        case ${JSON.stringify(flag)}: {`,
            `          const __gen_value = ${tsParseValue(listRef, "__gen_take()")};`,
            `          ${name} ??= [];`,
            `          ${name}.push(__gen_value);`,
            "          break;",
            "        }",
          );
        } else {
          declarations.push(`      const ${name}: ${tsType(base)} = [];`);
          cases.push(
            `        case ${JSON.stringify(flag)}: {`,
            `          const __gen_value = ${tsParseValue(listRef, "__gen_take()")};`,
            `          ${name}.push(__gen_value);`,
            "          break;",
            "        }",
          );
        }
      } else if (cliBool(base)) {
        declarations.push(`      let ${name}: boolean | undefined;`);
        cases.push(
          `        case ${JSON.stringify(flag)}: ${name} = true; break;`,
          `        case ${JSON.stringify(`--no-${param.name}`)}: ${name} = false; break;`,
        );
      } else {
        declarations.push(`      let ${name}: ${tsType(base)} | undefined;`);
        cases.push(
          `        case ${JSON.stringify(flag)}: ${name} = ${tsParseValue(base, "__gen_take()")}; break;`,
        );
      }
      if (!optional && !cliList(base)) {
        finals.push(
          `      if (${name} === undefined) throw new Error(${JSON.stringify(`missing ${flag}`)});`,
        );
      }
    }

    cliTs.push(
      `    case ${JSON.stringify(entry.verb)}: {`,
      ...declarations,
      "      for (let __gen_index = 0; __gen_index < args.length; __gen_index += 1) {",
      "        const __gen_argument = args[__gen_index];",
      "        const __gen_equals = __gen_argument.indexOf(\"=\");",
      "        const __gen_flag = __gen_equals >= 0 ? __gen_argument.slice(0, __gen_equals) : __gen_argument;",
      "        const __gen_inline = __gen_equals >= 0 ? __gen_argument.slice(__gen_equals + 1) : undefined;",
      "        const __gen_take = (): string => {",
      "          if (__gen_inline !== undefined) return __gen_inline;",
      "          __gen_index += 1;",
      "          const __gen_value = args[__gen_index];",
      '          if (__gen_value === undefined) throw new Error(`${__gen_flag} needs a value`);',
      "          return __gen_value;",
      "        };",
      "        switch (__gen_flag) {",
      ...cases,
      "          default:",
      '            throw new Error(`unknown flag \\`${__gen_argument}\\``);',
      "        }",
      "      }",
      ...finals,
      `      const __gen_client = new ${entry.client.className}(transport);`,
    );
    const result = returnRef(entry.fn);
    const call = `__gen_client.${camel(entry.fn.name)}(${argsUsed.join(", ")})`;
    if (result === null) {
      cliTs.push(`      await ${call};`, '      return "null";');
    } else {
      cliTs.push(`      return JSON.stringify(await ${call});`);
    }
    cliTs.push("    }");

    // Rust arm
    const rustDeclarations: string[] = [];
    const rustCases: string[] = [];
    const rustFinals: string[] = [];
    const rustArgs: string[] = [];
    for (const param of entry.fn.params) {
      const base = cliBase(param.type);
      const optional = isOption(param.type);
      const name = `__arg_${snake(param.name)}`;
      const flag = `--${param.name}`;
      rustArgs.push(name);
      if (cliList(base)) {
        const listRef = witType(doc, base as number).kind.list;
        if (optional) {
          rustDeclarations.push(`        let mut ${name}: Option<Vec<${rustType(listRef)}>> = None;`);
          rustCases.push(
            `            ${JSON.stringify(flag)} => {`,
            `                let __gen_value = ${rustParseValue(
              listRef,
              `next_value(args, &mut __gen_index, __gen_inline, ${JSON.stringify(flag)})?`,
            )};`,
            `                ${name}.get_or_insert_with(Vec::new).push(__gen_value);`,
            "            }",
          );
        } else {
          rustDeclarations.push(`        let mut ${name}: Vec<${rustType(listRef)}> = Vec::new();`);
          rustCases.push(
            `            ${JSON.stringify(flag)} => {`,
            `                let __gen_value = ${rustParseValue(
              listRef,
              `next_value(args, &mut __gen_index, __gen_inline, ${JSON.stringify(flag)})?`,
            )};`,
            `                ${name}.push(__gen_value);`,
            "            }",
          );
        }
      } else if (cliBool(base)) {
        rustDeclarations.push(`        let mut ${name}: Option<bool> = None;`);
        rustCases.push(
          `            ${JSON.stringify(flag)} => ${name} = Some(true),`,
          `            ${JSON.stringify(`--no-${param.name}`)} => ${name} = Some(false),`,
        );
      } else {
        rustDeclarations.push(`        let mut ${name}: Option<${rustType(base)}> = None;`);
        rustCases.push(
          `            ${JSON.stringify(flag)} => ${name} = Some(${rustParseValue(
            base,
            `next_value(args, &mut __gen_index, __gen_inline, ${JSON.stringify(flag)})?`,
          )}),`,
        );
      }
      if (!optional && !cliList(base)) {
        rustFinals.push(
          `        let ${name} = ${name}.ok_or_else(|| ClientError::new(${JSON.stringify(
            `missing ${flag}`,
          )}))?;`,
        );
      } else {
        rustFinals.push(`        let ${name} = ${name};`);
      }
    }

    cliRust.push(
      `        ${JSON.stringify(entry.verb)} => {`,
      ...rustDeclarations,
      "            let mut __gen_index = 0;",
      "            while __gen_index < args.len() {",
      "                let __gen_argument = &args[__gen_index];",
      "                let (__gen_flag, __gen_inline) = match __gen_argument.split_once('=') {",
      "                    Some((__gen_flag, __gen_value)) => (__gen_flag, Some(__gen_value)),",
      "                    None => (__gen_argument.as_str(), None),",
      "                };",
      "                match __gen_flag {",
      ...rustCases,
      "                    _ => return Err(ClientError::new(format!(\"unknown flag `{__gen_argument}`\"))),",
      "                }",
      "                __gen_index += 1;",
      "            }",
      ...rustFinals,
      `            let __gen_client = ${entry.client.className}::new(transport);`,
    );
    const rustResult = returnRef(entry.fn);
    const rustCall = `__gen_client.${snake(entry.fn.name)}(${rustArgs.join(", ")})`;
    if (rustResult === null) {
      cliRust.push(
        `            ${rustCall}?;`,
        '            Ok("null".to_string())',
      );
    } else {
      cliRust.push(
        `            let __gen_result = ${rustCall}?;`,
        "            serde_json::to_string(&__gen_result)",
        '                .map_err(|error| ClientError::new(format!("cannot encode the result: {error}")))',
      );
    }
    cliRust.push("        }");
  }

  cliTs.push(
    "    default:",
    '      throw new Error(`unknown verb \\`${verb}\\``);',
    "  }",
    "}",
    "",
  );
  cliRust.push(
    "        _ => Err(ClientError::new(format!(\"unknown verb `{verb}`\"))),",
    "    }",
    "}",
    "",
    "#[allow(dead_code)]",
    "fn next_value(",
    "    args: &[String],",
    "    index: &mut usize,",
    "    inline: Option<&str>,",
    "    flag: &str,",
    ") -> Result<String, ClientError> {",
    "    if let Some(value) = inline {",
    "        return Ok(value.to_string());",
    "    }",
    "    *index += 1;",
    "    args.get(*index)",
    "        .cloned()",
    "        .ok_or_else(|| ClientError::new(format!(\"{flag} needs a value\")))",
    "}",
    "",
  );

  const tsHttpFile = `${header}\n${httpExportsTs.join("\n")}\n`;
  const rustHttpFile = `${header}\n${httpExportsRust.join("\n")}\n`;

  const tsTypesFile = tsTypes.length
    ? `${header}\n${tsTypes.join("\n")}`
    : `${header}\n// No named types are used by the generated routes.\nexport {};\n`;
  const rustTypesFile = rustTypes.length
    ? `${header}\nuse serde::{Deserialize, Serialize};\n\n${rustTypes.join("\n")}`
    : `${header}\n// No named types are used by the generated routes.\n`;

  const tsCommands = [
    header,
    "export type CommandParam = { name: string; type: string; optional: boolean };",
    "export type Command = {",
    "  verb: string;",
    "  method: string | null;",
    "  path: string | null;",
    "  interface: string;",
    "  function: string;",
    "  params: CommandParam[];",
    "  returns: string;",
    "};",
    "",
    `export const commands: Command[] = ${JSON.stringify(commands, null, 2)};`,
    "",
  ].join("\n");

  const rustCommands = [
    header,
    "pub struct CommandParam {",
    "    pub name: &'static str,",
    "    pub r#type: &'static str,",
    "    pub optional: bool,",
    "}",
    "",
    "pub struct Command {",
    "    pub verb: &'static str,",
    "    pub method: Option<&'static str>,",
    "    pub path: Option<&'static str>,",
    "    pub interface: &'static str,",
    "    pub function: &'static str,",
    "    pub params: &'static [CommandParam],",
    "    pub returns: &'static str,",
    "}",
    "",
    "pub const COMMANDS: &[Command] = &[",
    ...commands.map((command) =>
      [
        "    Command {",
        `        verb: ${JSON.stringify(command.verb)},`,
        `        method: ${command.method ? `Some(${JSON.stringify(command.method)})` : "None"},`,
        `        path: ${command.path ? `Some(${JSON.stringify(command.path)})` : "None"},`,
        `        interface: ${JSON.stringify(command.interface)},`,
        `        function: ${JSON.stringify(command.function)},`,
        `        params: &[${command.params
          .map(
            (param: any) =>
              `CommandParam { name: ${JSON.stringify(param.name)}, r#type: ${JSON.stringify(
                param.type,
              )}, optional: ${param.optional} }`,
          )
          .join(", ")}],`,
        `        returns: ${JSON.stringify(command.returns)},`,
        "    },",
      ].join("\n"),
    ),
    "];",
    "",
  ].join("\n");

  const tsIndex = [
    header,
    'export * from "./transport";',
    'export * from "./types";',
    'export * from "./commands";',
    'export * from "./http";',
    'export * from "./cli";',
    "",
  ].join("\n");

  const rustLib = [
    header,
    "use std::fmt;",
    "",
    "#[derive(Debug, Clone)]",
    "pub struct ClientError {",
    "    pub message: String,",
    "}",
    "",
    "impl ClientError {",
    "    pub fn new(message: impl Into<String>) -> Self {",
    "        Self { message: message.into() }",
    "    }",
    "}",
    "",
    "impl fmt::Display for ClientError {",
    "    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {",
    "        formatter.write_str(&self.message)",
    "    }",
    "}",
    "",
    "impl std::error::Error for ClientError {}",
    "",
    "/// An HTTP request adapter. Implement it over a UDS (HTTP over the socket), TCP, or fetch.",
    "pub trait Transport {",
    "    fn request(&self, method: &str, path: &str, body: Option<&str>) -> Result<String, ClientError>;",
    "}",
    "",
    "pub fn query_value<T: serde::Serialize>(value: &T) -> Result<String, ClientError> {",
    "    let text = serde_json::to_string(value)",
    '        .map_err(|error| ClientError::new(format!("cannot encode a query value: {error}")))?;',
    '    let text = if text.starts_with(\'"\') {',
    "        serde_json::from_str::<String>(&text).unwrap_or_default()",
    "    } else {",
    "        text",
    "    };",
    "    Ok(percent_encoding::utf8_percent_encode(&text, percent_encoding::NON_ALPHANUMERIC).to_string())",
    "}",
    "",
    "pub mod commands;",
    "pub mod types;",
    ...generatedInterfaces.map((module) => `pub mod ${module};`),
    "pub mod http;",
    "pub mod cli;",
    "pub use commands::{Command, CommandParam, COMMANDS};",
    "pub use http::*;",
    "pub use cli::run;",
    ...(named.size > 0 ? ["pub use types::*;"] : []),
    "",
  ].join("\n");

  const tsTransport = `${header}\n/** An HTTP request adapter: UDS (HTTP over the socket), TCP, or fetch. */\nexport type Transport = (method: string, path: string, body?: string) => Promise<string>;\n`;
  const tsPackage = `${JSON.stringify(
    {
      name: "@anthracite/client",
      version: "0.5.0",
      private: true,
      type: "module",
      description: "Generated clients for Anthracite apps",
      exports: { ".": "./src/index.ts" },
      scripts: { test: "bun test", typecheck: "tsc --noEmit" },
      devDependencies: { typescript: "5.6.3" },
    },
    null,
    2,
  )}\n`;
  const cargo = `[package]
name = "anth-client"
version.workspace = true
edition.workspace = true
license.workspace = true
description = "Generated clients for Anthracite apps"

[dependencies]
serde = { version = "1", features = ["derive"] }
serde_json = "1"
percent-encoding = "2"

[dev-dependencies]
base64 = "0.22"
`;

  const files: Record<string, string> = {
    "sdk/ts/client/package.json": tsPackage,
    "sdk/ts/client/src/index.ts": tsIndex,
    "sdk/ts/client/src/transport.ts": tsTransport,
    "sdk/ts/client/src/types.ts": tsTypesFile,
    "sdk/ts/client/src/commands.ts": tsCommands,
    "sdk/ts/client/src/http.ts": tsHttpFile,
    "sdk/ts/client/src/cli.ts": cliTs.join("\n"),
    "sdk/rust/client/Cargo.toml": cargo,
    "sdk/rust/client/src/lib.rs": rustLib,
    "sdk/rust/client/src/types.rs": rustTypesFile,
    "sdk/rust/client/src/commands.rs": rustCommands,
    "sdk/rust/client/src/http.rs": rustHttpFile,
    "sdk/rust/client/src/cli.rs": cliRust.join("\n"),
  };
  for (let index = 0; index < generatedInterfaces.length; index += 1) {
    files[`sdk/ts/client/src/${generatedInterfaces[index]}.ts`] = tsInterfaces[index];
    files[`sdk/rust/client/src/${generatedInterfaces[index]}.rs`] = rustInterfaces[index];
  }
  for (const [relative, content] of Object.entries(files)) {
    if (relative.endsWith(".rs")) files[relative] = formatRust(content);
  }
  return { files };
}

const { files } = generate();
let stale = false;
for (const [relative, content] of Object.entries(files)) {
  const path = join(root, relative);
  if (check) {
    let actual = "";
    try {
      actual = readFileSync(path, "utf8");
    } catch {
      actual = "";
    }
    if (actual !== content) {
      console.error(`${relative} is stale; run \`bun scripts/codegen.ts ${appArg}\``);
      stale = true;
    }
  } else {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, content);
  }
}
if (stale) process.exit(1);
if (!check) console.log(`generated ${Object.keys(files).length} files for ${appArg}`);
